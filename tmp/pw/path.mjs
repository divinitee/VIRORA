import { chromium } from "playwright-core";
const b = await chromium.launch({ args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: 390, height: 780 }, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const day = (d) => new Date(Date.now() - d * 864e5).toISOString();
const att = [];
for (let i = 0; i < 12; i++) att.push({ user_email: "s@test.com", game: "grammar_practice", grammar_topic: "tenses.present.continuous-negative", correct: i % 4 !== 0, round_at: day(i < 6 ? 2 : 0) });
await p.route((u) => u.pathname.startsWith("/api/"), async (r) => {
  const u = r.request().url();
  if (/User\/me/.test(u)) return r.fulfill({ json: { id: "u1", email: "s@test.com", full_name: "Student", role: "user", user_type: "student", onboarding_completed: true } });
  if (/public-settings/.test(u)) return r.fulfill({ json: { id: "x", public_settings: { auth_required: false } } });
  if (/GrammarProfile/.test(u)) return r.fulfill({ json: [{ user_email: "s@test.com", overall_level: "A2", overall_confidence: 0.7, domains: {} }] });
  if (/GrammarAttempt/.test(u) && r.request().method() === "GET") return r.fulfill({ json: att });
  return r.fulfill({ json: [] });
});
p.on("console", (m) => { if (m.type() === "error" && !/Failed to load|404/.test(m.text())) console.log("CONSOLE", m.text().slice(0, 250)); });
p.on("pageerror", (e) => console.log("PAGEERROR", e.message.slice(0, 300)));
const txt = async () => (await p.evaluate(() => document.body.innerText)).replace(/\s+/g, " ");
const lang = process.argv[2] || "en";
await p.addInitScript((l) => { try { localStorage.setItem("virora_lang", l); localStorage.setItem("lang", l); } catch {} }, lang);
await p.goto("http://localhost:5173/grammar?access_token=fake", { waitUntil: "networkidle" });
await p.waitForTimeout(5000);
console.log("URL", p.url().replace("http://localhost:5173", ""));
const y0 = await p.evaluate(() => window.scrollY);
await p.mouse.wheel(0, -4000); await p.waitForTimeout(900);
const y1 = await p.evaluate(() => window.scrollY);
await p.mouse.wheel(0, 2500); await p.waitForTimeout(900);
const y2 = await p.evaluate(() => window.scrollY);
console.log("scrollY start/up/down:", y0, y1, y2, "docH", await p.evaluate(() => document.documentElement.scrollHeight));
await p.mouse.wheel(0, -4000); await p.waitForTimeout(600);
console.log("TOP:", (await txt()).slice(0, 260));
await p.screenshot({ path: "/tmp/pw/top.png" });

const { JSDOM } = require('jsdom');
const fs = require('fs');
const dom = new JSDOM('<!doctype html><div id="root"></div><div id="after"></div>', { runScripts: 'outside-only', pretendToBeVisual: true, url: 'https://x.test/' });
const w = dom.window;
w.matchMedia = w.matchMedia || (() => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} }));
w.IntersectionObserver = class { observe() {} disconnect() {} unobserve() {} };
w.ResizeObserver = class { observe() {} disconnect() {} unobserve() {} };
w.eval(fs.readFileSync('/tmp/comeback-bundle.js', 'utf8'));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const text = () => w.document.body.textContent;
const ok = (c, m) => { if (!c) { console.log('FAIL', m, '\n', text()); process.exit(1); } console.log('PASS', m); };
(async () => {
  w.__mount();
  await sleep(600);
  ok(text().includes('2-day streak'), 'streak shown');
  ok(text().includes('Best 5'), 'best streak');
  ok(text().includes('1,240 XP'), 'xp counter');
  ok(text().includes("Today's done"), 'today done status');
  ok(text().includes('Come back tomorrow: +100 XP for a 3-day streak'), 'tomorrow hook');
  ok(text().includes('Keep going'), 'secondary CTA when done');
  ok(text().includes('Vira picked it for you'), 'coach line');
  ok(text().includes('12/20') && text().includes('Answer 20 questions'), 'effort mission progress');
  ok(text().includes('2-day streak bonus'), 'streak bonus row');
  const claims = () => [...w.document.querySelectorAll('#root button')].filter((b) => b.textContent.includes('Claim'));
  ok(claims().length === 2, 'two claim buttons: bonus + show_up');
  ok(claims()[0].textContent.includes('+100'), 'bonus is listed first');
  claims()[0].dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  await sleep(500);
  ok(w.__calls.some((c) => c[0] === 'claimMission' && c[1].mission_id === 'streak_2'), 'bonus claim sent');
  ok(text().includes('1,340 XP'), 'xp updated after bonus');
  claims()[0].dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  await sleep(500);
  ok(w.__calls.some((c) => c[0] === 'claimMission' && c[1].mission_id === 'show_up'), 'mission claim sent');
  ok(text().includes('1,390 XP') && claims().length === 0, 'all claimed');
  ok(w.__lifted?.streak?.current === 2, 'state lifted to Home for the shared streak');
  w.__mountAfter();
  await sleep(600);
  const after = w.document.getElementById('after').textContent;
  ok(after.includes('2-day streak') && after.includes('Come back tomorrow'), 'after-practice card: streak + tomorrow hook');
  ok(!after.includes("Start today's practice") && !after.includes('Keep going'), 'after-practice card has no start button');
  console.log('all good');
  process.exit(0);
})();

const { JSDOM } = require('jsdom');
const fs = require('fs');
const dom = new JSDOM('<!doctype html><div id="root"></div>', { runScripts: 'outside-only', pretendToBeVisual: true, url: 'https://x.test/' });
const w = dom.window;
w.matchMedia = w.matchMedia || (() => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} }));
w.IntersectionObserver = class { observe() {} disconnect() {} unobserve() {} };
w.ResizeObserver = class { observe() {} disconnect() {} unobserve() {} };
w.eval(fs.readFileSync('/tmp/comeback-bundle.js', 'utf8'));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const text = () => w.document.body.textContent;
const ok = (c, m) => { if (!c) { console.log('FAIL', m, '\n', text()); process.exit(1); } console.log('PASS', m); };
(async () => {
  w.__mount();
  await sleep(600);
  ok(text().includes('3-day streak'), 'streak shown');
  ok(text().includes('Best 5'), 'best streak');
  ok(text().includes('1,240 XP'), 'xp counter');
  ok(text().includes("Today's done"), 'today done status');
  ok(text().includes('Keep going'), 'secondary CTA when done');
  ok(text().includes('Vira picked it for you'), 'coach line');
  ok(text().includes('12/20'), 'mission progress');
  const btn = [...w.document.querySelectorAll('button')].find((b) => b.textContent.includes('Claim +50 XP'));
  ok(!!btn, 'one claim button (show_up)');
  ok([...w.document.querySelectorAll('button')].filter((b) => b.textContent.includes('Claim')).length === 1, 'claimed mission has no button');
  btn.dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  await sleep(500);
  ok(w.__calls.some((c) => c[0] === 'claimMission' && c[1].mission_id === 'show_up'), 'claim sent with mission id only');
  ok(text().includes('1,290 XP'), 'xp updated after claim');
  ok(![...w.document.querySelectorAll('button')].some((b) => b.textContent.includes('Claim')), 'no claim buttons left');
  ok(w.__lifted?.streak?.current === 3, 'state lifted to Home for the shared streak');
  console.log('all good');
  process.exit(0);
})();
